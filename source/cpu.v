/*
All parts are connected
*/

module cpu(input clk,input reset);

/*Every i/o port for each module!*/
wire [31:0] pc, next_pc, instruction;
wire [31:0] rs1_data, rs2_data, write_data, immediate;
wire[31:0] alu_a, alu_b, alu_result;
wire[31:0] read_data, pcplus4;
wire[31:0] branch_target, jalr_target;
wire [3:0] alu_op;
wire [1:0] alu_src_a, wb_sel;

/*
mem_size tells data memory how much data to access:
00 -> byte
01 -> halfword
10 -> word

mem_unsigned tells data memory how to extend a load:
0 -> sign extend
1 -> zero extend
*/
wire [1:0] mem_size;
wire mem_unsigned;

wire alu_src_b, reg_write, mem_read, mem_write, branch, jal, jalr;
wire branch_taken;

/*Program counter */

program_counter pc_register(.clk(clk),.reset(reset),.next_program_counter(next_pc),.program_counter(pc));


/*instn memory*/
instruction_memory instn_mem (.address(pc), .instruction(instruction));

// Keep incrementing pc by 4
assign pcplus4 = pc + 32'd4;

/* register file*/

register_file reg_file(.clk(clk),.we(reg_write),.rs1(instruction[19:15]),.rs2(instruction[24:20]),.rd(instruction[11:7]), .wd(write_data),.rd1(rs1_data),.rd2(rs2_data));

/*imm generator*/

immediate_generator imm_gen(.inst(instruction),.imm(immediate));

// cu

control_unit cu (
    .opcode(instruction[6:0]),.funct3(instruction[14:12]),.funct7(instruction[31:25]),
    .alu_op(alu_op),.alu_src_a(alu_src_a),.alu_src_b(alu_src_b),
    .reg_write(reg_write),.mem_write(mem_write),.mem_read(mem_read),.wb_sel(wb_sel),
    .branch(branch),.jal(jal),.jalr(jalr),

    /*
    These two signals are generated by the control unit
    and tell data memory whether the operation is byte,
    halfword or word, and whether a load is signed/unsigned.
    */
    .mem_size(mem_size),.mem_unsigned(mem_unsigned)
);

// choosing which data goes into alu as input 'a' determined by control signal in cu

assign alu_a = (alu_src_a == 2'd00) ? rs1_data : (alu_src_a == 2'd1) ? pc : 32'd0;
// alu_src_a = 0 -> rs1's data, 1-> pc, 2 -> no src so zero

// choosing which data goes into alu as input 'b' determined by alu_src_b control signal

assign alu_b = alu_src_b ? immediate : rs2_data;
// alu_src_b = 0 -> rs2_data, 1 -> immediate

// alu -> alu_op is generated by control unit too... we get alu_result.
alu actual_alu(.a(alu_a),.b(alu_b),.op(alu_op),.y(alu_result));



/*branch unit*/

branch_unit branching(.rs1_val(rs1_data),.rs2_val(rs2_data),.funct3(instruction[14:12]),.is_branch_taken(branch_taken));

// branch_taken -> condition is true or not, branch tells this is a branch instruction

// Data memory
data_memory data_mem (
    .clk(clk),
    .mem_write(mem_write),
    .mem_read(mem_read),

    /*
    mem_size tells data memory whether this is:
    byte (00), halfword (01), or word (10).

    mem_unsigned tells data memory whether LB/LH
    should sign-extend or LBU/LHU should zero-extend.
    */
    .mem_size(mem_size),
    .mem_unsigned(mem_unsigned),

    .address(alu_result),
    .wdata(rs2_data),
    .rdata(read_data)
);

// what to write back is governed by wb_sel

assign write_data = (wb_sel == 2'd0) ? alu_result : (wb_sel==2'd1) ? read_data : pcplus4;
// if wb_sel = 0-> alu_result is written back into rd, 1 -> data read from main memory is written into rd, 2 -> pc+4;

// next branch target for Jal and SB
assign branch_target = pc + immediate;
// for jalr_target -> clear the bit no. 0
assign jalr_target = (rs1_data + immediate) & 32'hFFFFFFFE;

// which pc to take! this will  be assigned to program_counter in program_counter module and given as an output(unless of course reset is high)
assign next_pc = jalr ? jalr_target : (jal || (branch && branch_taken)) ? branch_target : pcplus4;
// if jalr -> jalr_target is next pc, else in case or jal and a branch instruction of SB choose branch_target(pc+imm), else no branch instruction so go with pcplus4


endmodule